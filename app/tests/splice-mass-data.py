#!/usr/bin/env python3
"""v488: splice the generated Mass datasets from
app/worker/src/mass-order.ts into the APP_JS data block in
app/worker/src/client.ts (between the __MASS_DATA__
markers). Carries MASS_ORDER + MASS_LATIN (the standing
texts) and MASS_ROLES + MASS_LATIN_ROLES (v488's role
annotation) in one pass, so the client copy can never
drift from the generator's record."""
import re

SRC = '/home/hatch/workspace/.worktrees/v488/app/worker/src/mass-order.ts'
DST = '/home/hatch/workspace/.worktrees/v488/app/worker/src/client.ts'

src = open(SRC, encoding='utf-8').read()
body = src[src.index('export const MASS_ORDER'):]
body = body.replace('export const MASS_ORDER: Record<string, string[]> = ', 'var MASS_ORDER = ')
body = body.replace('export const MASS_LATIN: Record<string, string[]> = ', 'var MASS_LATIN = ')
body = body.replace('export const MASS_ROLES: Record<string, string> = ', 'var MASS_ROLES = ')
body = body.replace('export const MASS_LATIN_ROLES: Record<string, string> = ', 'var MASS_LATIN_ROLES = ')
assert 'export const' not in body

client = open(DST, encoding='utf-8').read()
a = client.index('/*__MASS_DATA__*/') + len('/*__MASS_DATA__*/')
b = client.index('/*__/MASS_DATA__*/')
head = ('\n/* v486: the fixed Order of Mass segments + the proven\n'
        '   Latin of the Ordinary parts (generated by\n'
        '   app/tests/gen-mass-order.py from the proven source\n'
        '   pages; see the release document section 3). */\n')
client = client[:a] + head + body + client[b:]
open(DST, 'w', encoding='utf-8').write(client)
print('spliced', len(body), 'chars into client.ts')
